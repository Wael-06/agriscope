document.addEventListener("DOMContentLoaded", () => {
  initAppShell("advisor", { showContextBar: true });

  document.querySelectorAll(".prompt-chip").forEach((chip) => {
    chip.addEventListener("click", () => {
      document.getElementById("advisor-question").value = chip.dataset.prompt;
    });
  });

  document.getElementById("advisor-form").addEventListener("submit", (e) => {
    e.preventDefault();
    requestFieldAdvice();
  });
});

async function requestFieldAdvice() {
  const btn = document.getElementById("advisor-btn");
  const empty = document.getElementById("advisor-empty");
  const output = document.getElementById("advisor-output");
  const status = document.getElementById("advisor-status");
  const factsEl = document.getElementById("advisor-facts");
  const cardsEl = document.getElementById("advisor-cards");
  const sourcesBox = document.getElementById("advisor-sources-box");
  const sourcesList = document.getElementById("advisor-sources");

  btn.disabled = true;
  btn.textContent = "Generating advice…";
  empty.classList.add("hidden");
  output.classList.remove("hidden");
  status.className = "banner banner-info";
  status.textContent = "Analyzing NASA observations, irrigation balance, and rotation scores…";
  factsEl.replaceChildren();
  cardsEl.replaceChildren();
  sourcesList.replaceChildren();
  sourcesBox.classList.add("hidden");

  try {
    const language = document.getElementById("advisor-language").value;
    const question = document.getElementById("advisor-question").value.trim() || null;
    const payload = {
      ...buildRecommendationPayload(getFieldState()),
      language,
      question
    };

    const result = await postAdvisor(payload);
    status.className = result.used_llm ? "banner banner-info" : "banner banner-warn";
    status.textContent = result.used_llm
      ? "Personalized guidance generated by Google Gemini using AgriScope's calculated field metrics."
      : result.error?.includes("GEMINI_API_KEY")
        ? "Gemini API key is not configured. Showing AgriScope's built-in rule-based field guidance."
        : "Gemini is currently unavailable. Showing built-in rule-based field guidance.";

    const isArabic = language === "ar";
    cardsEl.dir = isArabic ? "rtl" : "ltr";
    renderAdvisorFacts(factsEl, result.facts, isArabic);
    renderAdvisorCards(cardsEl, result.advice);

    (result.sources || []).forEach((src) => {
      if (!src.url || !src.url.startsWith("https://")) return;
      const li = document.createElement("li");
      const a = document.createElement("a");
      a.href = src.url;
      a.target = "_blank";
      a.rel = "noopener noreferrer";
      a.textContent = src.title || src.url;
      li.appendChild(a);
      sourcesList.appendChild(li);
    });
    if (sourcesList.childElementCount > 0) sourcesBox.classList.remove("hidden");
  } catch (err) {
    status.className = "banner banner-error";
    status.textContent = `Unable to retrieve advice: ${err.message}. Verify the backend is running on port 8000.`;
  } finally {
    btn.disabled = false;
    btn.textContent = "Refresh advice";
  }
}

function renderAdvisorFacts(container, facts, isArabic) {
  if (!facts) return;
  const nf = new Intl.NumberFormat(isArabic ? "ar" : "en", { maximumFractionDigits: 1 });
  const items = [];
  if (Number.isFinite(facts.yield?.kg_per_ha)) {
    items.push(["Yield estimate", `${nf.format(facts.yield.kg_per_ha)} kg/ha`, facts.yield.confidence ? `Confidence: ${facts.yield.confidence}` : ""]);
  }
  if (Number.isFinite(facts.water?.gap_7d_mm)) {
    items.push(["7-day water gap", `${nf.format(facts.water.gap_7d_mm)} mm`, facts.water.status || ""]);
  }
  if (Number.isFinite(facts.ndvi?.trend_60d)) {
    const t = facts.ndvi.trend_60d;
    items.push(["NDVI trend", `${t > 0 ? "+" : ""}${t.toFixed(2)}`, "Past 60 days"]);
  }

  items.forEach(([label, val, sub]) => {
    const div = document.createElement("div");
    div.className = "advisor-fact-card";
    div.innerHTML = `<span>${label}</span><strong>${val}</strong>${sub ? `<small>${sub}</small>` : ""}`;
    container.appendChild(div);
  });
}

function renderAdvisorCards(container, text) {
  const headings = {
    summary: "Summary",
    "this season": "This season",
    water: "Water",
    "soil and nutrients": "Soil and nutrients",
    "next seasons": "Next seasons",
    "risks to watch": "Risks to watch"
  };
  const pattern = /^\s*(?:#{1,3}\s*)?(?:\*\*)?(Summary|This season|Water|Soil and nutrients|Next seasons|Risks to watch)(?:\*\*)?\s*:?\s*(.*?)\s*$/i;
  const sections = [];
  let current = null;

  (text || "").split(/\r?\n/).forEach((line) => {
    const m = line.match(pattern);
    if (m) {
      current = { title: headings[m[1].toLowerCase()], items: [] };
      sections.push(current);
      if (m[2]) current.items.push(cleanLine(m[2]));
    } else if (line.trim()) {
      if (!current) {
        current = { title: "Field Guidance", items: [] };
        sections.push(current);
      }
      current.items.push(cleanLine(line));
    }
  });

  sections.filter((s) => s.items.length).forEach((sec, i) => {
    const card = document.createElement("article");
    card.className = "advisor-section-card" + (sec.title === "Summary" ? " summary-card" : "");
    const itemsHtml = sec.items.map((t) => `<li>${escapeHtml(t)}</li>`).join("");
    card.innerHTML = `
      <h3><span class="advisor-num">${String(i + 1).padStart(2, "0")}</span><span>${sec.title}</span></h3>
      <ul>${itemsHtml}</ul>
    `;
    container.appendChild(card);
  });
}

function cleanLine(line) {
  return line.trim().replace(/^(?:[-*•]|\d+[.)])\s+/, "").replace(/\*\*/g, "");
}

function escapeHtml(str) {
  return str.replace(/[&<>"']/g, (m) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[m]));
}
